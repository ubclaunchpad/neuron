function CommandList({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.List>) {
  return (
    <CommandPrimitive.List
      data-slot="command-list"
      className={cn("max-h-75 overflow-x-hidden overflow-y-auto", className)}
      {...props}
    />
  );
}

const InfiniteCommandList = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive.List>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive.List> & {
    query: InfiniteQueryLike<any>;
    threshold?: number;
    loader?: React.ReactNode;
  }
>(({ query, threshold = 100, loader, children, onScroll, ...rest }, ref) => {
  const infiniteScroll = useInfiniteScroll(query, { threshold });
  const handleScroll: React.UIEventHandler<HTMLDivElement> = React.useCallback(
    (event) => {
      onScroll?.(event);
      infiniteScroll(event);
    },
    [onScroll, infiniteScroll],
  );

  return (
    <CommandList ref={ref} onScroll={handleScroll} {...rest}>
      {children}
      {query.isFetchingNextPage && (
        <div className="flex items-center justify-center px-3 py-2 text-xs text-muted-foreground">
          {loader ?? <Spinner />}
        </div>
      )}
    </CommandList>
  );
});
InfiniteCommandList.displayName = "InfiniteCommandList";

